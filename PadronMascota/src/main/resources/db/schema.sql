    proxima_dosis DATE,
    CONSTRAINT ck_vacunacion_fechas CHECK (proxima_dosis IS NULL OR proxima_dosis > fecha),
    CONSTRAINT fk_vacunacion_mascota FOREIGN KEY (id_mascota) REFERENCES mascota (id_mascota),
